/* Flashing is performed by ZX Spectrum ULA, and should be performed every 32
   frames according to some sites. As we're not aiming for cycle-correct, I
   randomly picked 8 and stuck with it.
*/
function periodicRefresh() {
    canvas_flash_timer++;
    if (canvas_flash_timer > 8) {
        canvas_flash_timer = 0;
        canvas_flash_value = !canvas_flash_value;
    }
    refreshCanvas();
}

function clearStatus() {
    current_status = "";
    current_status_type = STATUS_TYPES.NONE;
}

function getBaseUrl(page, subpage) {
    var index_url = BASE_URL + String(page).padStart(4, "0");
    if (subpage > -1 && current_subpage_max > 1) {
        return index_url + "." + String(subpage).padStart(2, "0");
    }
    return index_url;
}

function getIndexUrl() {
    return getBaseUrl(current_page, -1) + ".idx";
}

function getScreenUrl(page, subpage) {
    return getBaseUrl(page, subpage) + ".scr";
}

function getTokenUrl(page, subpage) {
    return getBaseUrl(page, subpage) + ".tkn";
}

function fetchIndex() {
    switch (current_page) {
        case 9999:
            setDebugIndex();
            return;
    }

    fetchRemoteIndex();
}

async function fetchRemoteIndex() {
    try {
        // Fetch the JSON file  
        const response = await fetch(getIndexUrl());

        // Check for HTTP errors  
        if (!response.ok) {
            throw new Error(`${response.status} ${response.statusText}`);
        }

        // Parse JSON data  
        const content = await response.text();
        if (content.length >= 3) {
            parseIndex(content);
        } else {
            setError("Empty index");
        }
    } catch (error) {
        setError(error.message);
        console.error("Failed to fetch data:", error);
    }

    refreshCanvas();
}

function fetchCurrent() {
    switch (current_page_type) {
        case PAGE_TYPES.DEBUG:
            generatePage(current_page, current_subpage);
            break;

        case PAGE_TYPES.GALLERY:
            fetchScreen(current_page, current_subpage);
            break;
        
        case PAGE_TYPES.SPECSCII:
            fetchTokens(current_page, current_subpage, current_page_attribute);
            break;

        case PAGE_TYPES.SCREEN:
            fetchScreen(current_page, -1);
            break;
    }
}

function setDebugIndex() {
    current_subpage = 0;
    current_subpage_max = 3;
    current_page_type = PAGE_TYPES.DEBUG;
    fetchCurrent();
}

function generatePage(page, subpage) {
    zx_clearMemory(0x00, zx_toAttribute(false, false, ATTRIBUTES.BLACK, ATTRIBUTES.WHITE))

    switch (subpage) {
        case 0:
            zx_setCursor(0, 2);
            zx_setFont(font_default);
            zx_printString("Default:", zx_toAttribute(false, true, ATTRIBUTES.BLACK, ATTRIBUTES.YELLOW));
            zx_setCursor(0, 3);
            zx_setFont(font_default);
            for (let i = 0; i < (font_default.length / 8); i++) {
                zx_printBytes(zx_getFontData(i));
            }

            zx_setCursor(0, 7);
            zx_setFont(font_default);
            zx_printString("Computer:", zx_toAttribute(false, true, ATTRIBUTES.BLACK, ATTRIBUTES.YELLOW));
            zx_setCursor(0, 8);
            zx_setFont(font_computer);
            for (let i = 0; i < (font_default.length / 8); i++) {
                zx_printBytes(zx_getFontData(i));
            }
            break;
        case 1:
        case 2:
            let x = 1;
            let y = 2;
            let start = (subpage == 1 ? 0 : 0xc8);
            let end = (subpage == 1 ? 0xc7 : 0xff);
            for (let i = start; i <= end; i++) {
                zx_setCursor(x, y);
                zx_printString(i.toString(16).padStart(2, '0'), i);
                y++;
                if (y >= (SCREEN_HEIGHT_CHARS - 2)) {
                    y = 2;
                    x += 3;
                }
            }
            break;
    }

    setResponse(String(page), STATUS_TYPES.OK);
    refreshCanvas();
}

function fetchNext() {
    if (current_subpage < (current_subpage_max - 1)) {
        current_subpage++;
        fetchCurrent();
    }
}

function fetchPrevious() {
    if (current_subpage > 0) {
        current_subpage--;
        fetchCurrent();
    }
}

async function fetchScreen(page, subpage) {
    try {
        // Fetch the JSON file  
        const fetch_url = getScreenUrl(page, subpage);
        const response = await fetch(fetch_url);

        // Check for HTTP errors  
        if (!response.ok) {
            throw new Error(`${response.status} ${response.statusText}`);
        }

        // Parse JSON data  
        const data = await response.bytes();
        if (data.length == memory.length) {
            for (var i = 0; i < memory.length; i++) {
                memory[i] = data[i];
            }
        } else {
            setError("Not SCR");
            console.error("Data not consistent with SCR:", data.length);
        }

        clearStatus();
    } catch (error) {
        console.error("Failed to fetch data:", error);
        setError(error.message);
    }

    refreshCanvas();
}

async function fetchTokens(page, subpage, default_attribute) {
    try {
        // Fetch the JSON file  
        const fetch_url = getTokenUrl(page, subpage);
        const response = await fetch(fetch_url);

        // Check for HTTP errors  
        if (!response.ok) {
            throw new Error(`${response.status} ${response.statusText}`);
        }

        // Parse JSON data  
        const data = await response.bytes();
        processTokens(data, default_attribute);
    
        clearStatus();
    } catch (error) {
        console.error("Failed to fetch data:", error);
        setError(error.message, false);
        return;
    }

    refreshCanvas();
}


const SPECSCII = {
    ENTER: 0x0d,
    INK: 0x10,
    PAPER: 0x11,
    FLASH: 0x12,
    BRIGHT: 0x13,
    CURSOR: 0x16
};

function processTokens(data, default_attribute) {
    if (default_attribute >= 0) {
        zx_clearAttributes(default_attribute);
    }

    zx_setCursor(0, 0);
    let position = 0;
    while (position < data.length) {
        // SPECSCII format constants
        // Stream format with embedded escape codes (ZX Spectrum BASIC control codes):
        // - 0x0D = Enter (CR+LF) - move to start of next line
        // - 0x10 XX = INK color (0-7)
        // - 0x11 XX = PAPER color (0-7)
        // - 0x12 XX = FLASH (0 or 1)
        // - 0x13 XX = BRIGHT (0 or 1)
        // - 0x14 XX = INVERSE (0 or 1) - swaps ink/paper
        // - 0x15 XX = OVER (0 or 1) - XOR mode
        // - 0x16 YY XX = AT row, col - position cursor
        // - 0x17 XX = TAB to column
        // - Other bytes = character codes (0x20-0x7F printable, 0x80-0xFF block graphics)

        const current_byte = data[position];
        switch (current_byte) {
            case SPECSCII.BRIGHT:
                position++;
                current_page_attribute = (current_page_attribute & 0xbf) | (data[position] << 6);
                position++;
                continue;
            
            case SPECSCII.CURSOR:
                // implementation untested
                position++;
                const set_x = data[position];
                position++;
                const set_y = data[position];
                position++;
                zx_setCursor(set_x, set_y);
                continue;

            case SPECSCII.ENTER:
                zx_setCursor(0, cursor_y + 1);
                position++;
                continue;
            
            case SPECSCII.INK:
                position++;
                current_page_attribute = (current_page_attribute & 0xf8) | data[position];
                position++;
                continue;

            case SPECSCII.FLASH:
                position++;
                current_page_attribute = (current_page_attribute & 0x7f) | (data[position] << 7);
                position++;
                continue;

            case SPECSCII.PAPER:
                position++;
                current_page_attribute = (current_page_attribute & 0xc7) | (data[position] << 3);
                position++;
                continue;
        }

        if (current_byte >= 0x20 && current_byte <= 0x7f) {
            zx_setAttribute(current_page_attribute);
            zx_printASCII(current_byte);
            position++;
            continue;
        }

        if (current_byte >= 0x80) {
            zx_setAttribute(current_page_attribute);
            zx_printGlyph(data[position]);
            position++;
            continue;
        }

        console.log("Unhandled sequence: ", "0x" + current_byte.toString(16));
        position++;
    }
}

function parseIndex(content) {
    current_subpage = 0;
    current_subpage_max = 1;
    var type = content.slice(0, 3);
    switch (type) {
        /* Gallery */
        case PAGE_TYPES.GALLERY:
            if (content.length < 5) {
                throw new Error("GAL malformed");
            }
            setResponse(content.slice(0, 3) + " " + content.slice(3, 5), STATUS_TYPES.OK);
            return parseGAL(content);

        /* Single screen */
        case PAGE_TYPES.SCREEN:
            setResponse(content.slice(0, 3), STATUS_TYPES.OK);
            return parseSCR(content);
        
        /* SPECSCII tokens */
        case PAGE_TYPES.SPECSCII:
            if (content.length < 7) {
                throw new Error("TKN malformed");
            }
            setResponse(content.slice(0, 3), STATUS_TYPES.OK);
            return parseTKN(content);
    }
    setError("Unknown type");
}

function parseGAL(content) {
    current_page_type = PAGE_TYPES.GALLERY;
    current_subpage_max = Number("0x" + content.slice(3, 5));
    fetchCurrent();
    return true;
}

function parseSCR(content) {
    current_page_type = PAGE_TYPES.SCREEN;
    fetchCurrent();
    return true;
}

function parseTKN(content) {
    current_page_type = PAGE_TYPES.SPECSCII;
    current_subpage_max = Number("0x" + content.slice(3, 5));
    current_page_attribute = Number("0x" + content.slice(5, 7));
    fetchCurrent();
    return true;
}

// The function gets called when the window is fully loaded
window.onload = function () {
    // Get the canvas and context
    canvas = document.getElementById("viewport");
    context = canvas.getContext("2d");
    canvas_width = canvas.width;
    canvas_height = canvas.height;
    canvas_image = context.createImageData(canvas_width, canvas_height);
    canvas_interval = setInterval(periodicRefresh, SCREEN_REFRESH);

    document.addEventListener('keyup', handleInput);
    function handleInput(event) {
        switch (event.key) {
            case "0":
            case "1":
            case "2":
            case "3":
            case "4":
            case "5":
            case "6":
            case "7":
            case "8":
            case "9":
                current_input = (current_input + event.key).slice(-4);
                break;
            case "Enter":
                var next_page = Number(current_input);
                if (next_page == 0) {
                    next_page = PAGE_DEFAULT;
                }
                current_page = next_page;
                current_input = "";
                fetchIndex();
                break;
            case "Escape":
                current_input = "";
                break;

            case "PageUp":
            case "ArrowUp":
            case "p":
                fetchPrevious();
                break;

            case "PageDown":
            case "ArrowDown":
            case "n":
                fetchNext();
                break;

            case "ArrowLeft":
                current_page--;
                if (current_page < PAGE_MINIMUM) current_page = PAGE_MINIMUM;
                fetchIndex();
                break;

            case "ArrowRight":
                current_page++;
                if (current_page > PAGE_MAXIMUM) current_page = PAGE_MAXIMUM;
                fetchIndex();
                break;

            }

        refreshCanvas();
    }

    zx_clearMemory(0, zx_toAttribute(false, true, ATTRIBUTES.BLACK, ATTRIBUTES.WHITE));
    refreshCanvas();
    fetchIndex();
};